#!/bin/bash
# Run on the SERVER once (and again after fetch-stock.sh): copies Qualcomm's perf client and the
# perf interface libraries it needs from the stock system_ext and system images into the marble
# tree, and registers only those this build does not already make. Writes
# device/xiaomi/marble/stock/miraperf/ (git-ignored with the rest of stock/).
set -e
T=~/aurora
FW=${1:-~/stock/fw}
D=$T/device/xiaomi/marble/stock/miraperf
INFO=$T/out/target/product/marble/module-info.json
SE=$(mktemp -d); SY=$(mktemp -d)
fsck.erofs --extract="$SE" "$FW/system_ext.img" >/dev/null
fsck.erofs --extract="$SY" "$FW/system.img" >/dev/null
rm -rf "$D"; mkdir -p "$D/system_ext/lib64" "$D/system/lib64"
BP="$D/Android.bp"; MK="$D/miraperf.mk"
echo "// Generated by setup-perf-libs.sh: Qualcomm perf client from the stock firmware." > "$BP"
echo "# Generated by setup-perf-libs.sh: Qualcomm perf client from the stock firmware." > "$MK"
echo "PRODUCT_PACKAGES += \\" >> "$MK"
# name:partition
for e in libqti-perfd-client_system:system_ext vendor.qti.hardware.perf@2.2:system_ext \
         vendor.qti.hardware.perf@2.3:system_ext vendor.qti.hardware.perf2-V1-ndk:system; do
  lib=${e%%:*}; part=${e##*:}
  # An interface library this tree builds from source: use that one, not the stock copy.
  if [ "$lib" != "libqti-perfd-client_system" ] && [ -f "$INFO" ] && grep -q "\"$lib\": {" "$INFO"; then
    echo "    $lib \\" >> "$MK"; echo "from source: $lib"; continue
  fi
  if [ "$part" = system ]; then src="$SY/system/lib64/$lib.so"; else src="$SE/lib64/$lib.so"; fi
  [ -f "$src" ] || src="$SE/lib64/$lib.so"
  [ -f "$src" ] || src="$SY/system/lib64/$lib.so"
  if [ ! -f "$src" ]; then echo "MISSING in stock: $lib"; continue; fi
  cp "$src" "$D/$part/lib64/$lib.so"
  m="miraclo_stock_${lib//[@.-]/_}"
  if [ "$part" = system_ext ]; then where="system_ext_specific: true,"; else where=""; fi
  cat >> "$BP" <<BPX

cc_prebuilt_library_shared {
    name: "$m",
    stem: "$lib",
    srcs: ["$part/lib64/$lib.so"],
    $where
    compile_multilib: "64",
    check_elf_files: false,
    strip: { none: true },
}
BPX
  echo "    $m \\" >> "$MK"
  echo "added $lib ($part)"
done
echo "" >> "$MK"
rm -rf "$SE" "$SY"
echo "miraperf.mk:"; cat "$MK"
