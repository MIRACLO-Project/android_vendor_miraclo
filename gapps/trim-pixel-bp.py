"""Keeps in vendor/miraclo/gapps/Android.bp only the Pixel modules gapps.mk installs (Google
Phone, Messages, Clock), so no other Pixel file is defined alongside MindTheGapps' copy. Those
apps are installed exactly as Google signed them (presigned, preprocessed).
Usage: trim-pixel-bp.py <vendor/miraclo/gapps>"""
import os, re, sys

G = sys.argv[1]
mk = open(os.path.join(G, "gapps.mk")).read()
want = set(re.findall(r"^\s+(MiraGms\S*)", mk, re.M))
bp_path = os.path.join(G, "Android.bp")
s = open(bp_path).read()

# Split into top-level blocks: `type {` ... matching `}`.
blocks, i = [], 0
while True:
    m = re.compile(r"^([a-z_]+)\s*\{", re.M).search(s, i)
    if not m:
        break
    depth, j = 0, m.end() - 1
    while True:
        if s[j] == "{":
            depth += 1
        elif s[j] == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    blocks.append((m.group(1), s[m.start():j + 1]))
    i = j + 1

names = {re.search(r'\bname:\s*"([^"]+)"', t).group(1) for _, t in blocks if re.search(r'\bname:\s*"([^"]+)"', t)}
removed = names - want
out, kept = ["// Generated by extract-gapps.sh, trimmed by trim-pixel-bp.py. Do not edit.", ""], []
for kind, text in blocks:
    n = re.search(r'\bname:\s*"([^"]+)"', text)
    if n and n.group(1) not in want:
        continue
    # References to removed modules (a support library MindTheGapps now provides, for example).
    for r in removed | {x for x in re.findall(r'"(MiraGms_[^"]+)"', text) if x not in want}:
        text = re.sub(r'\s*"%s",?' % re.escape(r), "", text)
    text = re.sub(r"\n\s*\w+:\s*\[\s*\],?", "", text)
    if kind == "android_app_import" and "presigned: true" in text:
        add = [l for l in ("preprocessed: true,",) if l.split(":")[0] not in text]
        if add:
            text = text.rstrip("}").rstrip() + "\n" + "".join("    %s\n" % l for l in add) + "}"
    out += [text, ""]
    if n:
        kept.append(n.group(1))
missing = sorted(want - set(kept))
# A module gapps.mk names may be defined in another folder (an overlay, for example).
missing = [m for m in missing if not any(
    ('"%s"' % m) in open(os.path.join(r, f)).read()
    for r, _, fs in os.walk(G) if "mtg" not in r for f in fs if f == "Android.bp" and os.path.join(r, f) != bp_path)]
if missing:
    sys.exit("trim-pixel-bp: not defined anywhere: " + ", ".join(missing))
open(bp_path, "w").write("\n".join(out))
print("Pixel modules kept: " + ", ".join(kept))
