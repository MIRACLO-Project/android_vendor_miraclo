"""Turns the unpacked MindTheGapps system/ tree in <dir> into build rules:
  <dir>/Android.bp   the apps, installed exactly as Google signed them (presigned, preprocessed)
  <dir>/Android.mk   the overlays, copied as they are into the partition's overlay folder
  <dir>/mtg.mk       the modules to install, and every other file (the Play services APEX,
                     permissions, sysconfig, libraries) copied to the same place
MindTheGapps is the source for everything it has; only Google Phone, Messages and Clock come
from the Pixel image (trim-pixel.py, trim-pixel-bp.py)."""
import os, sys

D = os.path.abspath(sys.argv[1])
SYS = os.path.join(D, "system")
REL = os.path.relpath(D, os.path.abspath(os.path.join(D, "../../../..")))  # vendor/miraclo/gapps/mtg

# Google's version of an AOSP app replaces it, as on Pixels.
OVERRIDES = {
    "GooglePackageInstaller": "PackageInstaller",
    "GoogleExtShared": "ExtShared",
    "GoogleExtServices": "ExtServices",
    "Velvet": "QuickSearchBox",
    "SetupWizard": "Provision",
}
# Not for this phone: the tablet build of the Google app (same package as Velvet, twice the
# size), and the scripts that keep GApps across flashes in other recoveries.
SKIP_APPS = {"VelvetTitan"}
SKIP_DIRS = ("addon.d",)

PART = {"product": "product_specific: true,", "system_ext": "system_ext_specific: true,"}
COPY_OUT = {"product": "$(TARGET_COPY_OUT_PRODUCT)", "system_ext": "$(TARGET_COPY_OUT_SYSTEM_EXT)",
            "system": "$(TARGET_COPY_OUT_SYSTEM)"}
MK_OUT = {"product": "$(TARGET_OUT_PRODUCT)", "system_ext": "$(TARGET_OUT_SYSTEM_EXT)",
          "system": "$(TARGET_OUT)"}

bp = ["// Generated by make-mtg.py from MindTheGapps. Do not edit.", ""]
mk = ["# Generated by make-mtg.py from MindTheGapps. Do not edit.", "LOCAL_PATH := $(call my-dir)", ""]
packages, copies = [], []
for root, dirs, files in os.walk(SYS):
    dirs.sort()
    rel = os.path.relpath(root, SYS)
    parts = rel.split(os.sep)
    if parts[0] in SKIP_DIRS:
        continue
    part = parts[0] if parts[0] in ("product", "system_ext") else "system"
    inner = parts[1:] if part != "system" else ([] if parts == ["."] else parts)
    for f in sorted(files):
        src = os.path.join(rel, f)
        stem = os.path.splitext(f)[0]
        if f.endswith(".apk") and len(inner) >= 2 and inner[0] in ("app", "priv-app"):
            if stem in SKIP_APPS:
                print("not installed: " + src)
                continue
            name = "MiraMtg_" + stem
            bp += ["android_app_import {",
                   '    name: "%s",' % name,
                   '    apk: "system/%s",' % src,
                   "    presigned: true,",
                   "    preprocessed: true,",
                   "    privileged: %s," % ("true" if inner[0] == "priv-app" else "false")]
            if part in PART:
                bp.append("    " + PART[part])
            if OVERRIDES.get(stem):
                bp.append('    overrides: ["%s"],' % OVERRIDES[stem])
            bp += ["    dex_preopt: { enabled: false },",
                   "    enforce_uses_libs: false,",
                   "}", ""]
            packages.append(name)
        elif f.endswith(".apk") and inner[:1] == ["overlay"]:
            name = "MiraMtg_" + stem
            mk += ["include $(CLEAR_VARS)",
                   "LOCAL_MODULE := " + name,
                   "LOCAL_MODULE_CLASS := APPS",
                   "LOCAL_MODULE_SUFFIX := .apk",
                   "LOCAL_CERTIFICATE := PRESIGNED",
                   "LOCAL_MODULE_PATH := %s/%s" % (MK_OUT[part], "/".join(inner)),
                   "LOCAL_SRC_FILES := system/" + src,
                   "LOCAL_REPLACE_PREBUILT_APK_INSTALLED := $(LOCAL_PATH)/system/" + src,
                   "LOCAL_DEX_PREOPT := false",
                   "include $(BUILD_PREBUILT)", ""]
            packages.append(name)
        elif f.endswith(".apk"):
            print("not installed (APK outside app, priv-app and overlay): " + src)
        else:
            dest = "/".join(inner + [f])
            copies.append("    %s/system/%s:%s/%s" % (REL, src, COPY_OUT[part], dest))

open(os.path.join(D, "Android.bp"), "w").write("\n".join(bp))
open(os.path.join(D, "Android.mk"), "w").write("\n".join(mk))
out = ["# Generated by make-mtg.py from MindTheGapps. Do not edit.", "", "PRODUCT_PACKAGES += \\"]
out += ["    %s \\" % p for p in packages[:-1]] + ["    %s" % packages[-1], ""]
if copies:
    out += ["PRODUCT_COPY_FILES += \\"] + [c + " \\" for c in copies[:-1]] + [copies[-1], ""]
open(os.path.join(D, "mtg.mk"), "w").write("\n".join(out))
print("MindTheGapps: %d apps and overlays, %d other files" % (len(packages), len(copies)))
