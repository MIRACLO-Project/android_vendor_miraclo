"""Before the build: every privileged Google app must have each privileged permission it asks
for allowlisted, or Android refuses to start at first boot. For every priv-app APK under
vendor/miraclo/gapps that is installed, this reads the permissions it asks for (aapt2), keeps the
platform's privileged ones, and allowlists whatever no permissions file covers yet, in
privapp-permissions-miraclo-gapps-generated.xml in the app's own partition.
Usage: check-privapp.py <tree>"""
import glob, os, re, subprocess, sys
import xml.etree.ElementTree as ET

T = os.path.abspath(sys.argv[1])
G = os.path.join(T, "vendor/miraclo/gapps")
ANDROID = "{http://schemas.android.com/apk/res/android}"

aapt2 = next((p for p in [os.path.join(T, "out/host/linux-x86/bin/aapt2"),
                          os.path.join(T, "prebuilts/sdk/tools/linux/bin/aapt2")] if os.path.exists(p)), None)
if not aapt2:
    sys.exit("check-privapp: aapt2 not found (build once, or check prebuilts/sdk)")

# 1. The platform's privileged permissions.
priv = set()
man = ET.parse(os.path.join(T, "frameworks/base/core/res/AndroidManifest.xml")).getroot()
for p in man.iter("permission"):
    level = p.get(ANDROID + "protectionLevel", "")
    if "privileged" in level:
        priv.add(p.get(ANDROID + "name"))

# 2. What is already allowlisted, per package.
allowed = {}
# Only files that are really installed: the MindTheGapps ones (all of them are), the platform's,
# and MIRACLO's own. The Pixel set's permission files are not installed any more.
for f in glob.glob(os.path.join(G, "mtg/**/*.xml"), recursive=True) + \
         glob.glob(os.path.join(T, "frameworks/base/data/etc/*.xml")) + \
         glob.glob(os.path.join(T, "device/xiaomi/marble/**/*.xml"), recursive=True) + \
         [x for x in glob.glob(os.path.join(T, "vendor/miraclo/**/privapp*.xml"), recursive=True)
          if not x.startswith(G + os.sep) or x.startswith(os.path.join(G, "mtg") + os.sep)]:
    if "generated" in f:
        continue
    try:
        root = ET.parse(f).getroot()
    except Exception:
        continue
    for pp in root.iter("privapp-permissions"):
        pkg = pp.get("package")
        s = allowed.setdefault(pkg, set())
        for perm in pp.iter("permission"):
            s.add(perm.get("name"))
        for perm in pp.iter("deny-permission"):
            s.add(perm.get("name"))

# 3. The installed privileged apps (modules named in gapps.mk / mtg.mk).
installed = set()
for mk in [os.path.join(G, "gapps.mk"), os.path.join(G, "mtg/mtg.mk")]:
    if os.path.exists(mk):
        installed |= set(re.findall(r"^\s+(\S+?)\s*\\?$", open(mk).read(), re.M))
apks = []
for bp in [os.path.join(G, "Android.bp"), os.path.join(G, "mtg/Android.bp")]:
    if not os.path.exists(bp):
        continue
    text = open(bp).read()
    for block in re.findall(r"android_app_import\s*\{(.*?)\n\}", text, re.S):
        name = re.search(r'name:\s*"([^"]+)"', block)
        apk = re.search(r'apk:\s*"([^"]+)"', block)
        if not name or not apk or name.group(1) not in installed:
            continue
        if not re.search(r"privileged:\s*true", block):
            continue
        part = "system_ext" if "system_ext_specific: true" in block else "product" if "product_specific: true" in block else "system"
        apks.append((os.path.join(os.path.dirname(bp), apk.group(1)), part))

def run(*a):
    return subprocess.run([aapt2, *a], capture_output=True, text=True).stdout

missing = {}
for apk, part in apks:
    pkg = re.search(r"(\S+)", run("dump", "packagename", apk) or " ?")
    pkg = pkg.group(1) if pkg else None
    if not pkg:
        print("could not read " + apk); continue
    asks = set(re.findall(r"uses-permission(?:-sdk-23)?: name='([^']+)'", run("dump", "permissions", apk)))
    need = sorted((asks & priv) - allowed.get(pkg, set()))
    if need:
        missing.setdefault(part, {})[pkg] = need

# 4. Write the allowlists the apps still need.
for part in ("product", "system_ext", "system"):
    out = os.path.join(G, "privapp-permissions-miraclo-gapps-generated-%s.xml" % part)
    rows = missing.get(part, {})
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by check-privapp.py: privileged permissions the Google apps ask for",
             "     that no other permissions file allowlists. -->", "<permissions>"]
    for pkg in sorted(rows):
        lines.append('    <privapp-permissions package="%s">' % pkg)
        lines += ['        <permission name="%s"/>' % n for n in rows[pkg]]
        lines.append("    </privapp-permissions>")
    lines.append("</permissions>")
    open(out, "w").write("\n".join(lines) + "\n")
    for pkg in sorted(rows):
        print("%s (%s): allowlisted %d more: %s" % (pkg, part, len(rows[pkg]), ", ".join(rows[pkg])))

# 5. Install them.
mk = os.path.join(G, "gapps.mk")
s = open(mk).read()
if "privapp-permissions-miraclo-gapps-generated" not in s:
    s += ("\n# Allowlists made by check-privapp.py\nPRODUCT_COPY_FILES += \\\n"
          "    vendor/miraclo/gapps/privapp-permissions-miraclo-gapps-generated-product.xml:$(TARGET_COPY_OUT_PRODUCT)/etc/permissions/privapp-permissions-miraclo-gapps-generated.xml \\\n"
          "    vendor/miraclo/gapps/privapp-permissions-miraclo-gapps-generated-system_ext.xml:$(TARGET_COPY_OUT_SYSTEM_EXT)/etc/permissions/privapp-permissions-miraclo-gapps-generated.xml \\\n"
          "    vendor/miraclo/gapps/privapp-permissions-miraclo-gapps-generated-system.xml:$(TARGET_COPY_OUT_SYSTEM)/etc/permissions/privapp-permissions-miraclo-gapps-generated.xml\n")
    open(mk, "w").write(s)
print("Privileged permission check: %d apps checked, %d needed more." % (len(apks), sum(len(v) for v in missing.values())))
